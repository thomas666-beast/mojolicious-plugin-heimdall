#!/usr/bin/env perl
use Mojolicious::Lite -signatures;

# Local teaching app: bind to loopback, use test-only passwords, and do
# not expose this in-memory account store publicly.
my $secret = $ENV{HEIMDALL_SESSION_SECRET} // '';
die "Set HEIMDALL_SESSION_SECRET to at least 32 randomly generated bytes\n"
  unless length($secret) >= 32 && $secret ne app->moniker;
app->secrets([$secret]);
app->sessions->cookie_name('heimdall_demo');
app->sessions->samesite('Lax');
app->sessions->default_expiration(1800);
app->sessions->secure(1) if app->mode eq 'production';

my %users;
my %users_by_id;
plugin 'Heimdall', {
  auth => {
    load_user => sub ($app, $id) { $users_by_id{$id} },
  },
};

my $password = app->heimdall->password;
for my $account ([1, 'admin', 'HEIMDALL_ADMIN_PASSWORD'], [2, 'member', 'HEIMDALL_MEMBER_PASSWORD']) {
  my ($id, $name, $env) = @$account;
  next if $name eq 'member' && !defined $ENV{$env};
  my $plain = $ENV{$env} // '';
  die "Set $env to a local test password of 12 to 256 characters\n"
    unless length($plain) >= 12 && length($plain) <= 256;
  my $user = {id => $id, name => $name, role => $name, hash => $password->hash($plain)};
  $users{$name} = $users_by_id{$id} = $user;
}

hook before_dispatch => sub ($c) { $c->res->headers->cache_control('no-store') };

get '/' => sub ($c) { $c->redirect_to('/account') };
get '/login' => sub ($c) { $c->render(template => 'login', error => '') };

post '/login' => sub ($c) {
  return $c->render(status => 403, text => 'Invalid form session.')
    if $c->validation->csrf_protect->has_error('csrf_token');

  my $form = $c->req->body_params;
  my $name = $form->param('username') // '';
  my $pass = $form->param('password') // '';
  my $user = $users{$name};
  # Verify even for an unknown name so failed credential attempts take a
  # similar path. Production applications also need login throttling.
  my $ok = length($pass) <= 256 && $password->verify($pass, ($user // $users{admin})->{hash});
  return $c->render(status => 401, template => 'login', error => 'Invalid username or password.')
    unless $ok && $user;

  my $auth = $c->heimdall->auth;
  $auth->login($c, $user->{id});
  $c->res->code(303);
  return $c->redirect_to($auth->return_to($c, '/account'));
};

post '/logout' => sub ($c) {
  return $c->render(status => 403, text => 'Invalid form session.')
    if $c->validation->csrf_protect->has_error('csrf_token');
  $c->heimdall->auth->logout($c);
  $c->res->code(303);
  return $c->redirect_to('/login');
};

get '/account' => sub ($c) {
  my $auth = $c->heimdall->auth;
  $auth->require_login($c) or return;
  $c->render(template => 'account', user => $auth->current_user($c));
};

get '/admin' => sub ($c) {
  my $auth = $c->heimdall->auth;
  $auth->require_login($c) or return;
  return $c->render(status => 403, text => 'Administrator access required.')
    unless $auth->current_user($c)->{role} eq 'admin';
  $c->render(text => 'Admin area');
};

app->start;

__DATA__

